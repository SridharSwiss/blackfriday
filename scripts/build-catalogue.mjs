// Rebuilds src/data/catalogue.js from content/catalogue.txt.
// Format of the .txt: "## Category" headers, then "Name | spec" or "Name | spec | priceCHF".
import { readFileSync, writeFileSync } from "node:fs";

const src = readFileSync(new URL("../content/catalogue.txt", import.meta.url), "utf8");
const items = []; const seen = new Set(); let cat = null;
for (const raw of src.split("\n")) {
  const line = raw.trim();
  if (!line || line.startsWith("# ")) continue;
  if (line.startsWith("## ")) { cat = line.slice(3).trim(); continue; }
  const [name, spec = "", price] = line.split(" | ").map(s => s.trim());
  if (!cat || !name || seen.has(name.toLowerCase())) continue;
  seen.add(name.toLowerCase());
  const row = [cat, name, spec];
  if (price && !Number.isNaN(Number(price))) row.push(Number(price));
  items.push(row);
}
writeFileSync(new URL("../src/data/catalogue.js", import.meta.url),
  "/* GENERATED by scripts/build-catalogue.mjs from content/catalogue.txt. Edit the .txt and run `npm run catalogue`.\n   Format: [category, name, spec, priceCHF?] */\nexport default " + JSON.stringify(items) + ";\n");
console.log(`catalogue: ${items.length} products in ${new Set(items.map(i => i[0])).size} categories`);
